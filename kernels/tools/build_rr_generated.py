#!/usr/bin/env python3
"""Builds the native kernels that are partly generated from the user's own copy of the ray reconstruction library.

    python build_rr_generated.py [nvngx_dlssd.dll] [--arch gfx1100 ...]

Two kernels have stretches that are cheaper to translate than to re-derive: the encoder 0's gather of features from
the game's textures and its guide tail, and the last decoder's tail, which forms the network's outputs. This takes
each kernel's PTX out of the library (the fatbins in its image, PTX compressed with zstd), has gen_enc0.py /
gen_dec0_1.py write the generated stretches (rr2_enc0_gen.inc, rr2_dec0_1_gen.inc, beside the .hip that includes
them), builds the code objects for every architecture, and writes the manifest fragment
kernels/rr/kernels_rr_generated.txt that package.py and the runtime then pick up. None of the generated files are
committed: they are derived from NVIDIA's network and made here, from the copy the user has.

Needs the zstandard module (pip install zstandard) and what build_kernel.py needs.
"""
import hashlib
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KERNELS = os.path.dirname(HERE)
ROOT = os.path.dirname(KERNELS)
sys.path.insert(0, HERE)
sys.path.insert(0, KERNELS)

FATBIN = 0xBA55ED50

# kernel, generator, source (.hip) and code object name, manifest line
KERNELS_BUILT = [
    ("rr2_enc0_kernel", "gen_enc0.py", "rr2_enc0", "rr2_enc0_kernel rr2_enc0.hsaco block=32,1,1 args=1088 waves=4 entry=rr2_enc0_kernel_native"),
    ("rr2_dec0_kernel_1", "gen_dec0_1.py", "rr2_dec0_1", "rr2_dec0_kernel_1 rr2_dec0_1.hsaco block=32,1,1 args=216 waves=4 entry=rr2_dec0_kernel_1_native"),
]


def ptx_modules(dll):
    """Every PTX module in the library's fatbins."""
    import zstandard
    d = open(dll, "rb").read()
    for m in re.finditer(struct.pack("<I", FATBIN), d):
        o = m.start()
        hsz, = struct.unpack_from("<H", d, o + 6)
        fsz, = struct.unpack_from("<Q", d, o + 8)
        if hsz != 16 or not (0 < fsz < 200_000_000):
            continue
        e = o + hsz
        while e < o + hsz + fsz:
            kind, _, ehs = struct.unpack_from("<HHI", d, e)
            esz, = struct.unpack_from("<Q", d, e + 8)
            if kind == 1:
                csize, = struct.unpack_from("<I", d, e + 16)
                dsize, = struct.unpack_from("<Q", d, e + 56)
                payload = d[e + ehs:e + ehs + csize]
                try:
                    ptx = zstandard.ZstdDecompressor().decompress(payload, max_output_size=dsize)
                except Exception:
                    ptx = d[e + ehs:e + ehs + esz]
                if ptx[:8].startswith(b"//") or b".version" in ptx[:200]:
                    yield ptx.decode("utf-8", "replace")
            e += ehs + esz


def find_kernels(dll):
    from kernel_census import kernel_bodies
    wanted = {k[0] for k in KERNELS_BUILT}
    found = {}
    for text in ptx_modules(dll):
        if not any(w in text for w in wanted):
            continue
        for name, body in kernel_bodies(text):
            if name in wanted:
                found[name] = body
    missing = wanted - set(found)
    if missing:
        raise SystemExit("%s not in %s" % (", ".join(sorted(missing)), dll))
    return found


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dll = args[0] if args else os.path.join(ROOT, "third_party", "nvngx_dlssd.dll")
    arches = [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == "--arch"]
    if not os.path.isfile(dll):
        raise SystemExit("no library at %s" % dll)
    import build_kernel
    bodies = find_kernels(dll)
    manifest = []
    for kernel, generator, source, line in KERNELS_BUILT:
        body = bodies[kernel]
        digest = hashlib.sha256(body.encode("utf-8", "replace")).hexdigest()
        ptx_path = os.path.join(KERNELS, source + ".ptx")
        with open(ptx_path, "w", encoding="utf-8", newline=chr(10)) as f:
            f.write(body)
        print("%s: %d lines, sha256 %s" % (kernel, body.count(chr(10)) + 1, digest[:16]))
        subprocess.run([sys.executable, os.path.join(HERE, generator), ptx_path, os.path.join(KERNELS, source + "_gen.inc")], check=True)
        ok, report = build_kernel.build(source, arches or None)
        print(report)
        if not ok:
            raise SystemExit("build of %s failed" % source)
        manifest.append("# %s: the PTX with sha256 %s" % (kernel, digest))
        manifest.append(line)
    with open(os.path.join(KERNELS, "rr", "kernels_rr_generated.txt"), "w", encoding="utf-8", newline=chr(10)) as f:
        f.write("# Generated by build_rr_generated.py: do not edit" + chr(10))
        f.write(chr(10).join(manifest) + chr(10))
    print("built %s and kernels/rr/kernels_rr_generated.txt" % ", ".join(k[2] + ".hsaco" for k in KERNELS_BUILT))


if __name__ == "__main__":
    main()
