#!/usr/bin/env python3
"""The generated tail of the native rr2_dec0_kernel_1, from the user's PTX.

usage: gen_dec0_1.py <rr2_dec0_kernel_1.ptx> <out.inc>

The last decoder kernel is the stage every decoder shares up to the end of its MLP, and then forms y = r + m * s2 and
turns it into the network's outputs -- tanh and exponentials, a handful of texture-free formulas, five surface
writes -- in about a thousand instructions with nothing worth re-deriving. That tail is translated here
(ptx2hip.py). What it takes from the stage is registers: the destination registers of the last sixteen mmas (the MLP
sum m, one 16x8 tile per register pair) and the sixty-four f16 registers that hold the residual r in the same
fragment layout; both are filled from the stage's LDS arrays by pack_fragments. A few registers of index arithmetic
the PTX computed long before are recomputed by a prologue of their own defining instructions.

Writes <out.inc>: struct Regs, dec0_tail and pack_fragments. Derived from NVIDIA's network: never committed.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptx2hip  # noqa: E402
from gen_enc0 import REG, dests, statements  # noqa: E402


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read()
    lines = text.split("\n")
    param = re.search(r"\.param \.align \d+ \.b8 (\w+)\[", text).group(1)
    mma_lines = [i for i, l in enumerate(lines) if "mma.sync" in l]
    first, last_start = mma_lines[0], mma_lines[-1]
    last_end = last_start
    while ";" not in lines[last_end]:
        last_end += 1
    ret_line = next(i for i in range(last_end, len(lines)) if lines[i].strip() == "ret;")
    mma_re = re.compile(r"mma\.sync[^{]*\{([^}]*)\}\s*,\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}\s*,\s*\{([^}]*)\}")
    mmas = []
    for start, st in statements(lines, first, last_end):
        m = mma_re.search(st)
        if m:
            mmas.append([[r.strip() for r in g.split(",")] for g in m.groups()])
    tiles = mmas[-16:]                        # tile k = 4 * token block + 8-channel block
    d_regs = [r for t in tiles for r in t[0]]

    tail_used = set()
    for i in range(last_end + 1, ret_line + 1):
        tail_used |= set(REG.findall(lines[i]))
    lastdef = {}
    for i in range(0, last_end + 1):
        for r in dests(lines[i]):
            lastdef[r] = i

    # the residual: f16 registers the tail adds the scaled m to
    tail_text = "\n".join(lines[last_end + 1:ret_line + 1])
    unpack = {}                                # D register -> (low half register, high half register)
    for m in re.finditer(r"mov\.b32\s*\{\s*(%rs\d+)\s*,\s*(%rs\d+)\s*\}\s*,\s*(%r\d+)\s*;", tail_text):
        unpack[m.group(3)] = (m.group(1), m.group(2))
    scaled = {}                                # m half -> its product with s2
    for m in re.finditer(r"mul\.f16\s+(%rs\d+)\s*,\s*(%rs\d+)\s*,\s*(%rs\d+)\s*;", tail_text):
        scaled[m.group(2)] = m.group(1)
    partner = {}                               # product -> the residual register added to it
    for m in re.finditer(r"add\.f16\s+(%rs\d+)\s*,\s*(%rs\d+)\s*,\s*(%rs\d+)\s*;", tail_text):
        partner[m.group(2)] = m.group(3)
    residual = {}                              # (tile, register, half) -> residual register
    for k, t in enumerate(tiles):
        for q, d in enumerate(t[0]):
            for h, half in enumerate(unpack[d]):
                residual[(k, q, h)] = partner[scaled[half]]
    r_regs = sorted(set(residual.values()), key=lambda r: int(r[3:]))
    assert all(r in lastdef and r not in d_regs for r in r_regs), "a residual register is not defined before the tail"

    # everything else the tail reads that was defined before: recomputed, by its defining instructions
    others = sorted((tail_used & set(lastdef)) - set(d_regs) - set(r_regs))
    need, stack, picked = set(), list(others), set()
    while stack:
        r = stack.pop()
        if r in need or r not in lastdef:
            continue
        need.add(r)
        i = lastdef[r]
        picked.add(i)
        for s in set(REG.findall(lines[i])) - {r}:
            if s in lastdef and s not in d_regs and s not in r_regs:
                stack.append(s)
    prologue = [lines[i].strip().rstrip(";") for i in sorted(picked)]

    fields = []
    for r in sorted(set(d_regs) | set(r_regs), key=lambda r: (re.match(r"%([a-z]+)", r).group(1), int(re.search(r"\d+", r).group()))):
        fields.append("    %s %s;" % (ptx2hip.CTYPE[re.match(r"%([a-z]+)", r).group(1)], ptx2hip.cname(r)))
    tail = ptx2hip.translate(lines, param, last_end + 2, ret_line + 1, "dec0_tail", ins=d_regs + r_regs, outs=[], prologue=prologue)

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by gen_dec0_1.py from %s. Derived from NVIDIA's network: do not commit.\n" % os.path.basename(src))
        f.write("struct Regs {\n" + "\n".join(fields) + "\n};\n\n")
        f.write(tail + "\n")
        f.write("// m (the MLP sum) and r (the residual), [64 tokens][32 channels] f16, into the registers of lane (g, t):\n")
        f.write("// tile k = 4 * token block + 8-channel block, register q holds row g + 8q, columns 2t and 2t + 1\n")
        f.write("__device__ inline void pack_fragments(Regs &io, const uint16_t *m, const uint16_t *r, int lane) {\n")
        f.write("    const int g = lane >> 2, t = lane & 3;\n")
        for k, tile in enumerate(tiles):
            tb, nt = k // 4, k % 4
            for q, d in enumerate(tile[0]):
                base = "(%d + g + %d) * 32 + %d + 2 * t" % (16 * tb, 8 * q, 8 * nt)
                f.write("    io.%s = *(const uint32_t *)(m + %s);\n" % (ptx2hip.cname(d), base))
                for h in range(2):
                    f.write("    io.%s = r[%s + %d];\n" % (ptx2hip.cname(residual[(k, q, h)]), base, h))
        f.write("}\n")
    print("tail in: %d m registers, %d residual registers, prologue of %d instructions" % (len(d_regs), len(r_regs), len(prologue)))


if __name__ == "__main__":
    main()
