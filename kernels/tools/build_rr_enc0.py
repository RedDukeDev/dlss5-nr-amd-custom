#!/usr/bin/env python3
"""Builds the native rr2_enc0_kernel from the user's own copy of the ray reconstruction library.

    python build_rr_enc0.py [nvngx_dlssd.dll] [--arch gfx1100 ...]

The encoder 0 gathers its features from the game's textures in thousands of instructions that are cheaper to
translate than to re-derive. This takes the kernel's PTX out of the library (the fatbins in its image, PTX
compressed with zstd), has gen_enc0.py write its two generated stretches (rr2_enc0_gen.inc, beside rr2_enc0.hip),
builds rr2_enc0.hsaco for every architecture, and writes the manifest fragment kernels/rr/kernels_rr_enc0.txt that
package.py and the runtime then pick up. None of the generated files are committed: they are derived from NVIDIA's
network and made here, from the copy the user has.

Needs the zstandard module (pip install zstandard) and what build_kernel.py needs.
"""
import hashlib
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KERNELS = os.path.dirname(HERE)
ROOT = os.path.dirname(KERNELS)
sys.path.insert(0, HERE)
sys.path.insert(0, KERNELS)

KERNEL = "rr2_enc0_kernel"
FATBIN = 0xBA55ED50


def ptx_modules(dll):
    """Every PTX module in the library's fatbins."""
    import zstandard
    d = open(dll, "rb").read()
    for m in re.finditer(struct.pack("<I", FATBIN), d):
        o = m.start()
        hsz, = struct.unpack_from("<H", d, o + 6)
        fsz, = struct.unpack_from("<Q", d, o + 8)
        if hsz != 16 or not (0 < fsz < 200_000_000):
            continue
        e = o + hsz
        while e < o + hsz + fsz:
            kind, _, ehs = struct.unpack_from("<HHI", d, e)
            esz, = struct.unpack_from("<Q", d, e + 8)
            if kind == 1:
                csize, = struct.unpack_from("<I", d, e + 16)
                dsize, = struct.unpack_from("<Q", d, e + 56)
                payload = d[e + ehs:e + ehs + csize]
                try:
                    ptx = zstandard.ZstdDecompressor().decompress(payload, max_output_size=dsize)
                except Exception:
                    ptx = d[e + ehs:e + ehs + esz]
                if ptx[:8].startswith(b"//") or b".version" in ptx[:200]:
                    yield ptx.decode("utf-8", "replace")
            e += ehs + esz


def find_kernel(dll):
    from kernel_census import kernel_bodies
    for text in ptx_modules(dll):
        if KERNEL not in text:
            continue
        for name, body in kernel_bodies(text):
            if name == KERNEL:
                return body
    raise SystemExit("%s is not in %s" % (KERNEL, dll))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dll = args[0] if args else os.path.join(ROOT, "third_party", "nvngx_dlssd.dll")
    arches = [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == "--arch"]
    if not os.path.isfile(dll):
        raise SystemExit("no library at %s" % dll)
    body = find_kernel(dll)
    digest = hashlib.sha256(body.encode("utf-8", "replace")).hexdigest()
    ptx_path = os.path.join(KERNELS, "rr2_enc0.ptx")
    with open(ptx_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("%s: %d lines, sha256 %s" % (KERNEL, body.count("\n") + 1, digest[:16]))
    subprocess.run([sys.executable, os.path.join(HERE, "gen_enc0.py"), ptx_path, os.path.join(KERNELS, "rr2_enc0_gen.inc")], check=True)
    import build_kernel
    ok, report = build_kernel.build("rr2_enc0", arches or None)
    print(report)
    if not ok:
        raise SystemExit("build failed")
    with open(os.path.join(KERNELS, "rr", "kernels_rr_enc0.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by build_rr_enc0.py from the PTX with sha256 %s: do not edit\n" % digest)
        f.write("%s rr2_enc0.hsaco block=32,1,1 args=1088 waves=4 entry=rr2_enc0_kernel_native\n" % KERNEL)
    print("built rr2_enc0.hsaco and kernels/rr/kernels_rr_enc0.txt")


if __name__ == "__main__":
    main()
